"""Prompt 定义。

⚠️ 这里记录一个实测踩出来的坑：**工具调用协议不是框架无关的**。

Prompt 早期带有这种写法：

    [TOOL_CALL:note:{"action":"create","task_id":1,...}]

这是一种**文本协议式的"伪工具调用"** —— 模型把工具调用写成一整段特殊文本，
再由框架解析出来去执行。

但 LangChain / LangGraph 用的是**原生 function calling**：
工具的 JSON Schema 通过 API 的 `tools` 参数传给模型，模型返回结构化的
`tool_calls` 字段，由 `ToolNode` 执行。**模型根本不需要在正文里写任何调用语法。**

没改这些 prompt 直接跑，结果是：规划专家老老实实输出了 `[TOOL_CALL:note:...]`，
但 plan 节点是个**不带工具的普通 LLM 调用**，没人解析这段文本，
模型也就没再输出任务 JSON —— 最后**静默**退化成兜底任务「基础背景梳理」。
（静默是关键：不报错，只是结果变得平庸，很容易被忽略。）

修复方式就是把 `[TOOL_CALL:...]` 那几段删掉：

    * planner：删掉 <NOTE_COLLAB> / <TOOLS>，只保留 <GOAL> / <FORMAT>
    * summarizer：删掉 <NOTES>
    * reporter：删掉 <NOTES>

**结论：「Prompt 是框架无关的」这句话只对了一半 ——
业务描述确实无关，但工具调用协议是强耦合的。**
"""

from datetime import datetime


def get_current_date() -> str:
    """当前日期，注入 Prompt 让模型知道"今天是几号"。"""

    return datetime.now().strftime("%B %d, %Y")


